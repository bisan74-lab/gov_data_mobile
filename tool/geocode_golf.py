REGION_DROP = re.compile(r'(특별자치도|특별자치시|특별시|광역시|도)$')
METRO = {"광주","대구","대전","부산","서울","울산","인천"}


def unit_of(region, addr):
    toks = addr.strip().split()
    if region in METRO:  # 광역시/특별시 → 구/군
        for t in toks:
            if t.endswith(("구", "군")) and not REGION_DROP.search(t):
                return t
    for t in toks:  # 도 → 시 우선, 없으면 군
        if t.endswith("시") and not REGION_DROP.search(t):
            return t
    for t in toks:
        if t.endswith("군"):
            return t
    for t in toks:
        if t.endswith("구"):
            return t
    return None


def jitter(seed):
    h = hashlib.md5(seed.encode("utf-8")).digest()
    dy = (h[0] / 255 - 0.5) * 0.09  # ±0.045°
    dx = (h[1] / 255 - 0.5) * 0.09
    return dy, dx


def main():
    rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig")))
    seen_loc, out, skipped = {}, [], []
    for r in rows:
        region = r["지역"].strip()
        addr = r["소재지"].strip()
        name = r["이름"].strip()
        u = unit_of(region, addr)
        table = C.get(region, {})
        base = table.get(u)
        if base is None and region == "인천":
            base = table.get("인천시")
        if base is None and region == "세종":
            base = table.get("세종특별자치시")
        if base is None:
            skipped.append((region, u, addr))
            continue
        # dedup by (name, addr) — 같은 클럽의 홀/구분 중복행은 홀 큰 것만.
        holes = int(re.sub(r"[^0-9]", "", r["홀"]) or "18")
        key = (name, addr)
        if key in seen_loc and holes <= seen_loc[key]["holes"]:
            continue
        dy, dx = jitter(addr + name)
        seen_loc[key] = {
            "name": name, "region": region, "addr": addr,
            "lat": base[0] + dy, "lon": base[1] + dx,
            "holes": holes, "type": r["구분"].strip(),
        }
    out = list(seen_loc.values())

    def dstr(s):
        return s.replace("\\", "").replace("'", "’").replace("$", "").strip()

    w = sys.stdout
    w.write("import 'models/golf_course.dart';\n\n")
    w.write("/// 전국 골프장(문화체육관광부_전국 골프장 현황, 자동 생성).\n")
    w.write("/// 좌표는 시/군/구 중심 + 소재지 기반 결정적 근사치(정밀 좌표는 추후 갱신).\n")
    w.write("/// 재생성: python3 tool/geocode_golf.py golf.csv\n")
    w.write("const List<GolfCourse> golfCourses = [\n")
    ids = set()
    for r in out:
        gid = "gc_" + hashlib.md5((r["name"] + r["addr"]).encode()).hexdigest()[:8]
        while gid in ids:
            gid += "x"
        ids.add(gid)
        w.write("  GolfCourse(\n")
        w.write(f"    id: '{gid}',\n")
        w.write(f"    name: '{dstr(r['name'])}',\n")
        w.write(f"    region: '{r['region']}',\n")
        w.write(f"    latitude: {r['lat']:.5f},\n")
        w.write(f"    longitude: {r['lon']:.5f},\n")
        w.write(f"    address: '{dstr(r['addr'])}',\n")
        w.write(f"    holes: {r['holes']},\n")
        w.write(f"    type: '{dstr(r['type'])}',\n")
        w.write("  ),\n")
    w.write("];\n")
    sys.stderr.write(f"생성 {len(out)}개 / 원본 {len(rows)}행, 건너뜀 {len(skipped)}\n")
    for s in skipped[:20]:
        sys.stderr.write(f"  SKIP {s}\n")


if __name__ == "__main__":
    main()
